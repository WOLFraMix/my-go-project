package main

import (
	"fmt"
	"io"
	"os"
)

func main() {
	filename := "example.txt"

	// Пытаемся вывести последние 3 строки файла.
	// Если возникает ошибка, выводим ее в консоль.
	if err := tail(filename, 3); err != nil {
		fmt.Printf("Ошибка в функции tail: %v\n", err)
	}
}

// tail выводит последние n строк из файла.
// Мы постарались сделать функцию, которая отработает за O(1) по памяти,
// функция не загружает весь файл в оперативную память, а читает его с конца.
func tail(filename string, n int) error {
	// Если просят 0 или меньше строк, нам нечего делать
	if n <= 0 {
		return nil
	}

	// Открываем файл
	file, err := os.Open(filename)
	if err != nil {
		return fmt.Errorf("open file: %w", err)
	}
	// Обязательно закрываем файл при выходе из функции, чтобы не было утечек ресурсов
	defer file.Close()

	// Получаем метаинформацию о файле (нам нужен его общий размер в байтах)
	stat, err := file.Stat()
	if err != nil {
		return fmt.Errorf("getting file info: %w", err)
	}

	fileSize := stat.Size()
	// Если файл абсолютно пустой (0 байт), выводить нечего
	if fileSize == 0 {
		return nil
	}

	// Самая сложная часть: ищем байт (offset), с которого начинаются нужные нам N строк
	offset, err := findStartOffset(file, fileSize, n)
	if err != nil {
		return fmt.Errorf("finding start offset: %w", err)
	}

	// Перемещаем "курсор" чтения файла на найденную позицию
	// io.SeekStart означает, что мы отсчитываем offset от самого начала файла
	if _, err := file.Seek(offset, io.SeekStart); err != nil {
		return fmt.Errorf("file seek: %w", err)
	}

	// Выводим результат.
	// io.Copy работает очень эффективно: он берет данные из файла и напрямую
	// перекладывает их в стандартный вывод (stdout), используя внутренние буферы ОС.
	if _, err := io.Copy(os.Stdout, file); err != nil {
		return fmt.Errorf("copy to stdout: %w", err)
	}

	return nil
}

// findStartOffset - это самая сложная часть алгоритма.
// Как это работает в целом:
// Мы не можем читать файл построчно с конца, потому что ОС так не умеет.
// Поэтому мы "откусываем" куски файла (чанки) с конца, загружаем их в память
// и уже в памяти ищем символы переноса строки ('\n') справа налево.
// Если в текущем куске не хватило строк, мы сдвигаемся еще левее и читаем
// следующий кусок.
func findStartOffset(file *os.File, fileSize int64, n int) (int64, error) {
	// Читаем блоками по 4 КБ. Это оптимальный размер для жестких дисков и SSD.
	const chunkSize = 4096
	buf := make([]byte, chunkSize)

	var linesFound int
	// currentPos - это "курсор", который указывает на начало того блока,
	// который мы сейчас будем читать. Изначально он стоит в самом конце файла.
	currentPos := fileSize

	// Цикл работает, пока мы не дойдем до начала файла (currentPos == 0)
	for currentPos > 0 {
		// В начале определяем, сколько байт нам нужно прочитать.
		// Обычно это 4096, но если мы подошли близко к началу файла,
		// остаток может быть меньше (например, может остаться только 100 байт).
		bytesToRead := min(currentPos, int64(chunkSize))

		// Сдвигаем наш глобальный курсор влево на размер блока
		currentPos -= bytesToRead

		// Физически перемещаем курсор файла на currentPos
		if _, err := file.Seek(currentPos, io.SeekStart); err != nil {
			return 0, fmt.Errorf("file seek: %w", err)
		}

		// Читаем из файла ровно столько байт, сколько рассчитали (bytesToRead).
		// Передавая подслайс buf[:bytesToRead], мы явно ограничиваем объем чтения.
		// Это решает сразу две задачи:
		// 1. io.ReadFull прочитает ровно столько, сколько осталось в начале файла, не пытаясь
		//    прочитать лишние данные (что спасет от избыточного чтения при больших файлах).
		//    Если файл большой, например на 5000 байт, а буфер только на 4096 байт, то при второй
		//    итерации мы прочитаем оставшиеся 904 байта, которые не читали в начале.
		// 2. Нам не придется обрабатывать ошибку io.ErrUnexpectedEOF, которая возникла бы,
		//    если бы мы попытались прочитать 4096 байт в файле, который весит меньше.
		if _, err := io.ReadFull(file, buf[:bytesToRead]); err != nil {
			return 0, fmt.Errorf("read block: %w", err)
		}

		// Ищем переносы строк ('\n') в прочитанном буфере.
		// Мы идем по буферу задом наперед (можно еще сказать - справа налево).
		for i := int(bytesToRead) - 1; i >= 0; i-- {
			if buf[i] == '\n' {
				// Если самый последний символ во всем файле - это '\n',
				// мы не должны считать его за перенос, иначе программа подумает,
				// что после него идет еще одна (пустая) строка.
				// Пример: файл "A\nB\n". Нам нужны 2 строки ("A" и "B"). Но если
				// посчитать последний '\n', тогда мы найдем пустую строку и "B",
				// вместо нужных нам значений.
				isLastByteOfFile := (currentPos + int64(i)) == (fileSize - 1)
				if isLastByteOfFile {
					continue // Пропускаем этот '\n' и ищем дальше
				}

				// Нашли полноценный конец строки, прибавляем единицу к счетчику.
				linesFound++

				// Проверяем, собрали ли мы нужное количество строк.
				if linesFound == n {
					// Как вычислить финальную позицию?
					// currentPos -> начало текущего блока относительно начала файла
					// int64(i)   -> позиция найденного '\n' внутри блока
					// + 1        -> нам нужен текст сразу после переноса строки, а не сам '\n'
					return currentPos + int64(i) + 1, nil
				}
			}
		}
	}

	// Если цикл завершился, значит мы дошли до самого начала файла (0 байт),
	// но так и не нашли N переносов строк. Это значит, что в файле строк меньше, чем N.
	// В таком случае мы просто возвращаем 0, чтобы вывести весь файл целиком.
	return 0, nil
}
